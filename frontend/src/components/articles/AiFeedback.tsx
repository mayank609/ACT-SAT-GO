import { useState } from 'react';
import { Loader2, RefreshCw, Sparkles, ThumbsUp, TrendingUp } from 'lucide-react';
import toast from 'react-hot-toast';
import { api, type ArticleAiFeedback } from '../../lib/api';
import { Button } from '../common/Button';

// Claude's feedback on a submitted summary: score, strengths, what to improve
// and a short comment. While it is "pending" (API unavailable) it says so and
// offers a "Get feedback" button that retries.

const scoreTone = (n: number) =>
  n >= 8 ? 'bg-emerald-50 text-emerald-700 border-emerald-200'
    : n >= 5 ? 'bg-amber-50 text-amber-800 border-amber-200'
    : 'bg-red-50 text-red-700 border-red-200';

/** Small "AI 7/10" pill for lists and trackers. */
export function AiScoreBadge({ score, status }: { score?: number | null; status?: 'ready' | 'pending' | null }) {
  if (status === 'pending') {
    return <span className="inline-flex shrink-0 items-center gap-1 rounded-full border border-slate-200 bg-slate-50 px-2 py-0.5 text-[11px] font-bold text-slate-500">AI pending</span>;
  }
  if (typeof score !== 'number') return null;
  return (
    <span className={`inline-flex shrink-0 items-center gap-1 rounded-full border px-2 py-0.5 text-[11px] font-bold ${scoreTone(score)}`} title="AI feedback score">
      <Sparkles size={11} /> {score}/10
    </span>
  );
}

export function AiFeedbackPanel({
  articleId,
  feedback,
  studentId,
  manager,
  onUpdated,
}: {
  articleId: string;
  feedback: ArticleAiFeedback | null | undefined;
  /** Tutors/admins pass the student whose feedback to retry. */
  studentId?: string;
  manager?: boolean;
  onUpdated?: (fb: ArticleAiFeedback | null) => void;
}) {
  const [fb, setFb] = useState(feedback ?? null);
  const [busy, setBusy] = useState(false);

  const retry = async () => {
    setBusy(true);
    try {
      const r = await api.requestArticleFeedback(articleId, studentId);
      setFb(r.aiFeedback);
      onUpdated?.(r.aiFeedback);
      if (r.aiFeedback?.status !== 'ready') toast('Feedback is not available yet — try again in a little while.');
    } catch (e) {
      toast.error((e as Error).message || 'Could not get feedback');
    } finally {
      setBusy(false);
    }
  };

  if (!fb || fb.status === 'pending') {
    return (
      <div className="rounded-xl border border-slate-200 bg-slate-50 p-3 text-sm text-slate-600" aria-live="polite">
        <p className="flex items-center gap-1.5 font-semibold text-slate-700"><Sparkles size={14} className="text-violet-500" /> AI feedback</p>
        <p className="mt-1">Feedback will appear soon.</p>
        {manager && fb?.error && <p className="mt-1 text-[11px] text-slate-400 break-words">Last attempt: {fb.error}</p>}
        <Button className="mt-2" size="sm" variant="secondary" onClick={retry} loading={busy}
          icon={busy ? undefined : <RefreshCw size={13} />}>Get feedback</Button>
      </div>
    );
  }

  return (
    <div className="rounded-xl border border-violet-200 bg-violet-50/50 p-3 text-sm text-slate-700">
      <div className="flex items-center justify-between gap-2">
        <p className="flex items-center gap-1.5 font-semibold text-slate-800"><Sparkles size={14} className="text-violet-500" /> AI feedback</p>
        {typeof fb.score === 'number' && (
          <span className={`rounded-full border px-2.5 py-0.5 text-xs font-bold ${scoreTone(fb.score)}`}>{fb.score}/10</span>
        )}
      </div>
      {fb.comment && <p className="mt-2 leading-relaxed">{fb.comment}</p>}
      {!!fb.strengths?.length && (
        <div className="mt-3">
          <p className="flex items-center gap-1 text-xs font-bold uppercase tracking-wide text-emerald-700"><ThumbsUp size={12} /> What went well</p>
          <ul className="mt-1 list-disc space-y-1 pl-5">{fb.strengths.map((s, i) => <li key={i}>{s}</li>)}</ul>
        </div>
      )}
      {!!fb.improvements?.length && (
        <div className="mt-3">
          <p className="flex items-center gap-1 text-xs font-bold uppercase tracking-wide text-amber-700"><TrendingUp size={12} /> To improve</p>
          <ul className="mt-1 list-disc space-y-1 pl-5">{fb.improvements.map((s, i) => <li key={i}>{s}</li>)}</ul>
        </div>
      )}
      <p className="mt-3 text-[11px] text-slate-400">Generated by AI — your tutor still reviews your summary.</p>
    </div>
  );
}

/** Shown while a summary is being submitted and Claude is writing feedback. */
export function AiFeedbackLoading() {
  return (
    <div className="rounded-xl border border-violet-200 bg-violet-50/50 p-3 text-sm text-violet-900" role="status" aria-live="polite">
      <p className="flex items-center gap-2 font-semibold"><Loader2 size={15} className="animate-spin" /> Getting feedback on your summary…</p>
      <p className="mt-1 text-xs text-violet-700">This usually takes a few seconds.</p>
    </div>
  );
}
